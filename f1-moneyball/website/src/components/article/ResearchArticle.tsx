import { Link } from "react-router-dom";
import type { Article } from "../../lib/articles";
import {
  HowToCite, ArticleHeader, ArticleMetadata, ArticleSection, DataAvailability, HypothesisPanel, LimitationsPanel,
  MethodologyPanel, ReferencesList, ResearchQuestion, ResultsPanel, RobustnessTable, SECTIONS, TableOfContents,
} from "./ArticleParts";

const P = ({ items }: { items: string[] }) => <>{items.map((t) => <p key={t}>{t}</p>)}</>;
const n = (id: string) => SECTIONS.findIndex(([s]) => s === id) + 1;
const t = (id: string) => SECTIONS.find(([s]) => s === id)![1];

/** Fixed 14-section template used by every research article. */
export default function ResearchArticle({ a }: { a: Article }) {
  const S = (id: string, body: React.ReactNode) => <ArticleSection id={id} n={n(id)} title={t(id)}>{body}</ArticleSection>;
  return (
    <article>
      <ArticleHeader a={a} />
      <div className="mx-auto max-w-6xl px-5 py-10 grid grid-cols-1 lg:grid-cols-[15rem_minmax(0,1fr)] gap-12">
        <aside className="lg:sticky lg:top-6 self-start grid gap-8">
          <ArticleMetadata a={a} />
          <div className="hidden lg:block"><TableOfContents /></div>
          {a.interactive && <Link to={a.interactive.to} className="block bg-accent text-bg font-semibold text-sm px-4 py-3 hover:bg-accent-fg">{a.interactive.label} →</Link>}
          {a.paper && (
            <div className="grid gap-1 text-sm">
              <a href={import.meta.env.BASE_URL + a.paper.pdf} className="block border border-accent text-accent font-semibold px-4 py-3 hover:bg-accent hover:text-bg">Working paper (PDF) ↓</a>
              <a href={a.paper.source} className="text-muted underline px-1" target="_blank" rel="noreferrer">LaTeX source and code</a>
            </div>
          )}
        </aside>
        <div className="min-w-0">
          {S("question", <ResearchQuestion text={a.question} />)}
          {S("why", <P items={a.whyItMatters} />)}
          {S("literature", <P items={a.literature} />)}
          {S("hypotheses", <HypothesisPanel items={a.hypotheses} />)}
          {S("data", <><p>This article uses the datasets listed below. Their status, coverage and sources are generated by the data pipeline.</p><DataAvailability datasets={a.datasets} /></>)}
          {S("variables", (
            <dl className="grid gap-3 max-w-3xl">
              {a.variables.map((v) => (
                <div key={v.name} className="grid md:grid-cols-[12rem_1fr] gap-2 border-b border-line pb-3">
                  <dt className="num text-sm text-head">{v.name}<div className="text-xs text-muted">{v.dataset}</div></dt>
                  <dd className="text-sm">{v.definition}</dd>
                </div>
              ))}
            </dl>
          ))}
          {S("strategy", <MethodologyPanel steps={a.strategy} />)}
          {S("results", <ResultsPanel results={a.results} datasets={a.datasets} interactive={a.interactive?.to} basis={a.resultsBasedOn} />)}
          {S("robustness", a.robustnessResults?.length ? (
            <>
              <p>Checks run:</p>
              <ul>{a.robustness.map((r) => <li key={r}>{r}</li>)}</ul>
              <ResultsPanel results={a.robustnessResults} datasets={["robustness_checks"]} />
              <RobustnessTable study={a.slug} />
            </>
          ) : <><p>Planned checks. Each will be reported next to the main result it tests.</p><ul>{a.robustness.map((r) => <li key={r}>{r}</li>)}</ul></>)}
          {S("interpretation", a.interpretation.length ? <P items={a.interpretation} /> : <p>No interpretation is offered before results exist.</p>)}
          {S("limitations", <LimitationsPanel items={a.limitations} />)}
          {S("availability", <><p>All published data can be inspected and downloaded in the <Link className="underline decoration-accent" to="/data">Data Explorer</Link>, with its data dictionary and sources.</p><DataAvailability datasets={a.datasets} label="Datasets available to download" /></>)}
          {S("reproducibility", <ul>{a.reproducibility.map((r) => <li key={r}><code className="num text-xs bg-raise px-1 break-all">{r}</code></li>)}</ul>)}
          {S("references", <ReferencesList refs={a.references} />)}
          <HowToCite a={a} />
        </div>
      </div>
    </article>
  );
}
