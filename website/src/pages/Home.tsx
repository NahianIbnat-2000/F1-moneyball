function StatusFigures() {
  const statuses = useStatuses();
  const manifest = useManifest();
  if (statuses === undefined || manifest === undefined) return <p className="text-sm text-muted">Loading status…</p>;
  if (!statuses) return <p className="text-sm text-muted">Not yet published. The pipeline has not produced a status file.</p>;
  const all = Object.values(statuses);
  const pub = all.filter((d) => d.status === "published");
  const latest = pub.map((d) => d.last_updated).filter(Boolean).sort().at(-1) ?? null;
  const starts = pub.map((d) => d.coverage_start).filter((x): x is number => x !== null);
  const ends = pub.map((d) => d.coverage_end).filter((x): x is number => x !== null);
  const obs = pub.reduce((s, d) => s + d.observation_count, 0);
  const q = manifest?.quality;
  const rows: [string, string][] = [
    ["Published datasets", `${pub.length} of ${all.length}`],
    ["Data last updated", latest ? fmtDate(latest) : "Not yet published"],
    ["Seasons covered", starts.length ? `${Math.min(...starts)}–${Math.max(...ends)}` : "Not yet published"],
    ["Observations", obs ? obs.toLocaleString("en-US") : "None yet"],
    ["Articles with results", `${ARTICLES.filter((a) => a.publishedOn).length} of ${ARTICLES.length}`],
    ["Validation", q ? (q.n_errors ? `${q.n_errors} errors` : `Passed, ${q.n_warnings} warnings`) : "Not run"],
  ];
  return (
    <dl className="divide-y divide-line">
      {rows.map(([k, v], i) => (
        <div key={k} className="grid grid-cols-[2rem_1fr_auto] gap-3 py-2 text-sm items-baseline">
          <span aria-hidden className="num text-accent-fg">P{i + 1}</span><dt className="text-muted">{k}</dt><dd className="num text-fg text-right">{v}</dd>
        </div>
      ))}
    </dl>
  );
}

function DatasetLedger() {
  const statuses = useStatuses();
  const manifest = useManifest();
  if (!statuses) return null;
  return (
    <>
      <table className="w-full text-sm border-t-2 border-fg">
        <caption className="sr-only">Every dataset the research needs, with its current status</caption>
        <thead><tr className="border-b border-fg/70 text-left"><th scope="col" className="label py-2">Dataset</th><th scope="col" className="label py-2">Status</th><th scope="col" className="label py-2 text-right">Observations</th></tr></thead>
        <tbody>
          {Object.values(statuses).map((d) => (
            <tr key={d.dataset_id} className="border-b border-line">
              <td className="py-2.5 pr-3"><Link to={`/data?dataset=${d.dataset_id}`} className="hover:underline decoration-accent underline-offset-2">{d.dataset_name}</Link></td>
              <td className="py-2.5 pr-3"><StatusBadge status={d.status} /></td>
              <td className="py-2.5 num text-right text-muted">{d.observation_count || "–"}</td>
            </tr>
          ))}
        </tbody>
      </table>
      {manifest && <p className="mt-2 text-xs text-muted num">Generated by the data pipeline, {fmtDate(manifest.generated_at_utc)}{manifest.pipeline_commit ? `, commit ${manifest.pipeline_commit}` : ""}.</p>}
    </>
  );
}

